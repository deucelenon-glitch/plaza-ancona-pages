  var KEY = 'plaza-lang';
  /* expose a lookup so dynamically-rendered UI (order bar, checkout, ticket)
     can resolve an i18n key in the CURRENT language. */
  window.plazaT = function(key){
    var lang = document.documentElement.lang || 'it';
    var d = I18N[lang] || I18N.it;
    return (d && d[key] !== undefined) ? subst(d[key]) : undefined;
  };
  window.plazaLang = function(){ return document.documentElement.lang || 'it'; };
  /* turn @@token markers into inline SVG from window.ICONS */
  function subst(str) {
    return String(str).replace(/@@([a-z-]+)/g, function (m, name) {
      return (window.ICONS && window.ICONS[name]) || '';
    });
  }
  function apply(lang) {
    var dict = I18N[lang] || I18N.it;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (dict[k] !== undefined) el.innerHTML = subst(dict[k]);
    });
    if (typeof window.fillIcons === 'function') window.fillIcons();
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-ph');
      if (dict[k] !== undefined) el.placeholder = dict[k];
    });
    document.querySelectorAll('[data-lang]').forEach(function (b) {
      b.classList.toggle('on', b.getAttribute('data-lang') === lang);
    });
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    /* let dynamically-rendered UI (order bar, checkout, ticket) re-resolve text */
    try {
      document.dispatchEvent(new CustomEvent('plaza:lang', { detail: { lang: lang } }));
      window.dispatchEvent(new CustomEvent('plaza:lang', { detail: { lang: lang } }));
    } catch (e) {}
  }

  var saved = 'it';
  try { saved = localStorage.getItem(KEY) || 'it'; } catch (e) {}
  apply(saved);

  document.querySelectorAll('[data-lang]').forEach(function (b) {
    b.addEventListener('click', function () { apply(b.getAttribute('data-lang')); });
  });
